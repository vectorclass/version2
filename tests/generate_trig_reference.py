"""Decimal sin/cos/tan oracle using Machin's pi and reduced Taylor series.

No binary libm is used to evaluate references. --check compares 120/160 digits.
Inputs include adjacent binary values around quadrants, poles and range limits.
"""
import argparse
import decimal
import math
import pathlib
import random
import struct
D = decimal.Decimal


def arctan_inverse(n):
    x = D(1)/n
    term = total = x
    k = 1
    while True:
        term *= -x*x
        updated = total + term/(2*k+1)
        if updated == total: return total
        total = updated
        k += 1


def sincos(x, pi):
    if abs(x) < D(2)**-80: return x, D(1)
    q = (x/(pi/2)).to_integral_value(rounding=decimal.ROUND_HALF_EVEN)
    r = x-q*(pi/2)
    s = ts = r
    c = tc = D(1)
    k = 1
    while True:
        ts *= -r*r / ((2*k)*(2*k+1))
        tc *= -r*r / ((2*k-1)*(2*k))
        ns, nc = s+ts, c+tc
        if ns == s and nc == c: break
        s, c = ns, nc
        k += 1
    return [(s,c),(c,-s),(-s,-c),(-c,s)][int(q)%4]


def generate(precision):
    rows=[]
    with decimal.localcontext() as ctx:
        ctx.prec=precision
        pi=16*arctan_inverse(5)-4*arctan_inverse(239)
        for width,code,intcode,limit in [(32,'f','I',1.e7),(64,'d','Q',1.e15)]:
            def bits(x): return struct.unpack('>'+intcode,struct.pack('>'+code,x))[0]
            def value(i): return struct.unpack('>'+code,struct.pack('>'+intcode,i))[0]
            def quantize(x): return value(bits(float(x)))
            def neighbors(x):
                b=bits(quantize(x))
                return [value(i) for i in range(max(0,b-2),b+3)]
            def closest(y):
                center=bits(quantize(y))
                candidates=[i for i in [center-1,center,center+1] if 0<=i<1<<width and math.isfinite(value(i))]
                return min(candidates,key=lambda i:(abs(D.from_float(value(i))-y),i&1))
            rng=random.Random(0x519C05+width)
            xs=[0.,-0.,value(1),-value(1),math.ldexp(1.,-126 if width==32 else -1022)]
            for k in [0,1,2,3,4,7,8,17,100,1000,10000,1000000]+([10**8,10**10,10**12,10**14] if width==64 else []):
                xs+=neighbors(D(k)*pi/2)+neighbors((D(k)+D('.5'))*pi/2)
            for boundary in [1.e4,1.e5,1.e7]+([1.e8,1.e13,1.e15] if width==64 else []): xs+=neighbors(boundary)
            xs += [quantize(rng.uniform(0,limit)) for _ in range(200)]
            xs += [quantize(rng.uniform(0,1.e4 if width==32 else 1.e8)) for _ in range(100)]
            xs += [math.ldexp(1.,-i) for i in [10,24,53,80,100]]
            xs = [v*sign for v in xs if abs(v)<=limit for sign in [-1,1]]
            for xb in sorted({bits(x) for x in xs}):
                x=D.from_float(value(xb)); s,c=sincos(x,pi)
                for op,y in enumerate([s,c,s/c]): rows.append((width,op,xb,closest(y)))
    return sorted(rows)


def render(rows):
    text='// Generated by generate_trig_reference.py; do not hand-edit.\n'
    text+='#ifndef VCL_TEST_TRIG_REFERENCE_H\n#define VCL_TEST_TRIG_REFERENCE_H\n#include <cstdint>\n'
    text+='struct TrigReference { unsigned width, op; uint64_t input, expected; };\n'
    text+='static constexpr TrigReference trig_reference[] = {\n'
    text+=''.join(f'    {{{w},{op},0x{x:016x}ull,0x{y:016x}ull}},\n' for w,op,x,y in rows)
    return '/*\n * Copyright 2026 DigitalExpressions Sweden\n *\n * Licensed under the Apache License, Version 2.0 (the "License");\n * you may not use this file except in compliance with the License.\n * You may obtain a copy of the License at\n *\n *     https://www.apache.org/licenses/LICENSE-2.0\n *\n * Unless required by applicable law or agreed to in writing, software\n * distributed under the License is distributed on an "AS IS" BASIS,\n * WITHOUT WARRANTIES OR CONDITIONS OF ANY KIND, either express or implied.\n * See the License for the specific language governing permissions and\n * limitations under the License.\n */\n\n'+text+'};\n#endif\n'


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    parser.add_argument('--output',type=pathlib.Path,default=pathlib.Path(__file__).with_name('trig_reference.h'))
    args=parser.parse_args(); rows=generate(120)
    if args.check:
        assert rows==generate(160),'reference rounding changed at higher precision'
        assert args.output.read_text()==render(rows),'committed fixture differs'
    else: args.output.write_text(render(rows))
    print(f'{len(rows)} Decimal trig cases; precision=120'+('; 160-digit agreement checked' if args.check else ''))


if __name__=='__main__': main()
