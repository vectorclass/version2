"""Generate independent 80-bit references for the exact pinned x86 seed-1 inputs.

Decimal Machin/Taylor trig and Decimal ln use 120/180 digits. Neither binary
libm nor VCL evaluates expected values. --check regenerates keys already in the
header; --capture selects raw input streams captured from unchanged upstream
TestData. Unknown runtime inputs fail closed rather than using an inaccurate
fallback. This fixture is deliberately scoped to the selected pinned matrix.
"""
import argparse,decimal,hashlib,json,math,pathlib,re,struct
from generate_trig_reference import arctan_inverse,sincos
D=decimal.Decimal
OUTPUT=pathlib.Path(__file__).with_name('upstream_x86_reference_data.h')
GROUPS=[(32,0),(64,0),(64,1),(64,2),(64,3)]

def value(width,bits):return struct.unpack('<f' if width==32 else '<d',struct.pack('<I' if width==32 else '<Q',bits))[0]

def ieee80(y):
    sign=int(y.is_signed())<<15
    if not y:return 0,sign
    n,d=y.copy_abs().as_integer_ratio()
    e=n.bit_length()-d.bit_length()
    if (n<d<<e) if e>=0 else (n<<(-e)<d):e-=1
    shift=63-e
    a,b=(n<<shift,d) if shift>=0 else (n,d<<(-shift))
    q,r=divmod(a,b)
    q+=int(2*r>b or (2*r==b and q&1))
    if q==1<<64:q>>=1;e+=1
    assert 1<<63<=q<1<<64 and -16382<=e<=16383
    return q,sign|(e+16383)

def capture_keys(folder):
    records=json.loads((folder.parent/'capture.json').read_text());keys={g:set() for g in GROUPS}
    for record in records:
        name=record['target'];data=(folder/(record['mode']+'-'+name+'.bin')).read_bytes()
        assert hashlib.sha256(data).hexdigest()==record['input_sha256']
        width=32 if any(t in name for t in ['Vec4f','Vec8f','Vec16f']) else 64
        case=int(name.rsplit('_',1)[1]);op=0 if case==105 else {200:1,201:2,202:1,203:2,204:3}[case]
        for (bits,) in struct.iter_unpack('<Q',data):
            x=value(width,bits)
            if math.isfinite(x) and (op!=0 or x>-1):keys[(width,op)].add(bits)
    return {g:sorted(k) for g,k in keys.items()}

def header_keys(text):
    keys={}
    for w,op in GROUPS:
        body=re.search(r'x86_reference_'+str(w)+'_'+str(op)+r'\[\] = \{(.*?)\n\};',text,re.S).group(1)
        keys[w,op]=[int(m,16) for m in re.findall(r'\{0x([0-9a-f]+)ull,',body)]
        assert keys[w,op]==sorted(set(keys[w,op]))
    return keys

def generate(keys,precision):
    rows={};cache={}
    with decimal.localcontext() as ctx:
        ctx.prec=precision;pi=16*arctan_inverse(5)-4*arctan_inverse(239)
        for (w,op),bits_list in keys.items():
            group=[]
            for bits in bits_list:
                x=D.from_float(value(w,bits))
                if op==0:y=x if abs(x)<D(2)**-80 else (1+x).ln()
                else:
                    if bits not in cache:cache[bits]=sincos(x,pi)
                    s,c=cache[bits];y=s if op==1 else c if op==2 else s/c
                mantissa,exponent=ieee80(y);group.append((bits,mantissa,exponent))
            rows[w,op]=group
    return rows

def render(rows):
    text='// Generated by generate_upstream_x86_reference.py; Decimal 120/180-digit agreement.\n'
    text+='// Exact pinned upstream seed-1 inputs; expected values rounded to IEEE x87 extended precision.\n'
    text+='#ifndef VCL_TEST_UPSTREAM_X86_REFERENCE_DATA_H\n#define VCL_TEST_UPSTREAM_X86_REFERENCE_DATA_H\n#include <cstdint>\n'
    text+='struct X86ReferenceRow { uint64_t input, significand; uint16_t exponent; };\n'
    for (w,op),group in rows.items():
        text+=f'static constexpr X86ReferenceRow x86_reference_{w}_{op}[] = {{\n'
        text+=''.join(f'    {{0x{x:016x}ull,0x{m:016x}ull,0x{e:04x}}},\n' for x,m,e in group)
        text+='};\n'
    return '/*\n * Copyright 2026 DigitalExpressions Sweden\n *\n * Licensed under the Apache License, Version 2.0 (the "License");\n * you may not use this file except in compliance with the License.\n * You may obtain a copy of the License at\n *\n *     https://www.apache.org/licenses/LICENSE-2.0\n *\n * Unless required by applicable law or agreed to in writing, software\n * distributed under the License is distributed on an "AS IS" BASIS,\n * WITHOUT WARRANTIES OR CONDITIONS OF ANY KIND, either express or implied.\n * See the License for the specific language governing permissions and\n * limitations under the License.\n */\n\n'+text+'#endif\n'

def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--capture',type=pathlib.Path);parser.add_argument('--check',action='store_true');parser.add_argument('--output',type=pathlib.Path,default=OUTPUT);args=parser.parse_args()
    keys=capture_keys(args.capture) if args.capture else header_keys(args.output.read_text())
    a=generate(keys,120);b=generate(keys,180);assert a==b,'80-bit reference rounding changed at higher precision'
    text=render(a)
    if args.check:assert args.output.read_text()==text,'fixture differs'
    else:args.output.write_text(text)
    print('Independent 80-bit references:',{f'{w}:{op}':len(g) for (w,op),g in a.items()},'; 120/180-digit agreement; no libm/VCL oracle')
if __name__=='__main__':main()
