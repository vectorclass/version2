"""Independent hyperbolic fixtures using Decimal exp/ln/sqrt at 120/160 digits.

Binary libm supplies no reference values. Tiny odd functions round to their
input and tiny cosh rounds to one; large tanh rounds to one. Positive arguments
avoid inverse-function cancellation, then odd symmetry supplies negative ones.
"""
import argparse
import decimal
import math
import pathlib
import random
import struct

D = decimal.Decimal
OPS = ('sinh', 'cosh', 'tanh', 'asinh', 'acosh', 'atanh')


def generate(precision):
    rows = []
    with decimal.localcontext() as ctx:
        ctx.prec = precision
        ln2 = D(2).ln()
        for width, code, intcode, emin in [(32, 'f', 'I', -126), (64, 'd', 'Q', -1022)]:
            def bits(x): return struct.unpack('>'+intcode, struct.pack('>'+code, x))[0]
            def value(i): return struct.unpack('>'+code, struct.pack('>'+intcode, i))[0]
            def quantize(x): return value(bits(float(x)))
            def neighbors(x):
                b = bits(quantize(x))
                return [value(i) for i in range(max(0, b-3), min(1 << width, b+4)) if math.isfinite(value(i))]
            def closest(y):
                if y.is_zero(): return bits(float(y))
                center = bits(quantize(y))
                candidates = [i for i in [center-1, center, center+1] if 0 <= i < 1 << width and math.isfinite(value(i))]
                return min(candidates, key=lambda i: (abs(D.from_float(value(i))-y), i & 1))
            rng = random.Random(0x48B01C+width)
            normal = math.ldexp(1., emin)
            maximum = value(0x7f7fffff if width == 32 else 0x7fefffffffffffff)
            limit = quantize(89. if width == 32 else 709.7)
            tiny = [0., value(1), value(2), value(3), normal/2, normal]
            tiny += neighbors(normal)
            tiny += [math.ldexp(1., -e) for e in [10, 24, 53, 80, 100]]
            for op, name in enumerate(OPS):
                samples = tiny[:]
                for x in [.49, .5, .51, .533, .625, 1., 1.49, 2., 10.]: samples += neighbors(x)
                samples += [quantize(rng.random()*2) for _ in range(200)]
                if op < 2:
                    samples += neighbors(limit)
                    for k in [1, 2, 17, 100, 126 if width == 32 else 1022]:
                        for offset in [D(0), D('.5')]: samples += neighbors((D(k)+offset)*ln2)
                    samples += [quantize(rng.uniform(0, limit)) for _ in range(200)]
                    samples = [x for x in samples if 0 <= x < limit]
                elif op == 2:
                    for x in [20., 44.4, 350., maximum]: samples += neighbors(x)
                    samples += [value(rng.randrange(bits(normal), bits(maximum))) for _ in range(160)]
                elif op in [3, 4]:
                    for x in [1.e10, 1.e20, maximum, D.from_float(maximum).sqrt()]: samples += neighbors(x)
                    samples += [value(rng.randrange(bits(normal), bits(maximum))) for _ in range(200)]
                    if op == 4: samples = [x for x in samples if x >= 1]
                else:
                    samples += [quantize(rng.random()) for _ in range(200)]
                    samples = [x for x in samples if x < 1]
                for xb in sorted({bits(x*sign) for x in samples for sign in ([1] if op == 4 else [-1, 1])}):
                    a = value(xb); x = abs(D.from_float(a))
                    if op != 4 and x < D(2)**-80:
                        y = D(1) if op == 1 else D.from_float(a)
                    elif op == 0: y = (x.exp()-(-x).exp())/2
                    elif op == 1: y = (x.exp()+(-x).exp())/2
                    elif op == 2:
                        y = D(1) if x > 100 else (x*2).exp()
                        if x <= 100: y = (y-1)/(y+1)
                    elif op == 3: y = x.ln()+ln2 if x > D(2)**200 else (x+(x*x+1).sqrt()).ln()
                    elif op == 4: y = x.ln()+ln2 if x > D(2)**200 else (x+((x-1)*(x+1)).sqrt()).ln()
                    else: y = ((1+x)/(1-x)).ln()/2
                    if a < 0 and op != 1 and x >= D(2)**-80: y = -y
                    rows.append((width, op, xb, closest(y)))
    return rows


def render(rows):
    text = '// Generated by generate_hyperbolic_reference.py; do not hand-edit.\n'
    text += '#ifndef VCL_TEST_HYPERBOLIC_REFERENCE_H\n#define VCL_TEST_HYPERBOLIC_REFERENCE_H\n#include <cstdint>\n'
    text += 'struct HyperbolicReference { unsigned width, op; uint64_t input, expected; };\n'
    text += 'static constexpr HyperbolicReference hyperbolic_reference[] = {\n'
    text += ''.join(f'    {{{w},{op},0x{x:016x}ull,0x{y:016x}ull}},\n' for w, op, x, y in rows)
    return '/*\n * Copyright 2026 DigitalExpressions Sweden\n *\n * Licensed under the Apache License, Version 2.0 (the "License");\n * you may not use this file except in compliance with the License.\n * You may obtain a copy of the License at\n *\n *     https://www.apache.org/licenses/LICENSE-2.0\n *\n * Unless required by applicable law or agreed to in writing, software\n * distributed under the License is distributed on an "AS IS" BASIS,\n * WITHOUT WARRANTIES OR CONDITIONS OF ANY KIND, either express or implied.\n * See the License for the specific language governing permissions and\n * limitations under the License.\n */\n\n'+text+'};\n#endif\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--output', type=pathlib.Path, default=pathlib.Path(__file__).with_name('hyperbolic_reference.h'))
    args = parser.parse_args(); rows = generate(120)
    if args.check:
        assert rows == generate(160), 'reference rounding changed at higher precision'
        assert args.output.read_text() == render(rows), 'committed fixture differs'
    else: args.output.write_text(render(rows))
    print(f'{len(rows)} Decimal hyperbolic cases; precision=120'+('; 160-digit agreement checked' if args.check else ''))


if __name__ == '__main__': main()
